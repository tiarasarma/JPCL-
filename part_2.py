# 6. FULL ODE MODEL (SAME THREE-STEP MECHANISM AS PART 1)
# =====================================================================

def build_C(k):
    """
    Construct the cyclic catalytic transition matrix.
    """

    n = len(k)
    C = np.zeros((n, n))

    for i in range(n):

        C[i, i] = -k[i]
        C[(i + 1) % n, i] = k[i]

    return C


def steady_state_start(k):
    """
    Initial steady-state catalyst distribution
    without dissolution.
    """

    w = 1.0 / k

    return w / w.sum()


def lifetime_numeric(k, d, x0):
    """
    Calculate lifetime from the full ODE:

        dx/dt = (C-D)x

    Lifetime is the time at which total catalyst
    amount falls to 1/e of its initial value.
    """

    Mx = build_C(k) - np.diag(d)

    N0 = x0.sum()

    def event(t, x):

        return x.sum() - N0 / np.e

    event.terminal = True
    event.direction = -1

    # Eq. 7 estimate used to set the integration interval

    t_guess = (
        np.sum(1.0 / k)
        / np.sum(d / k)
    )

    sol = solve_ivp(
        lambda t, x: Mx @ x,
        (0, 1e3 * t_guess),
        x0,
        method="Radau",
        jac=lambda t, x: Mx,
        events=event,
        rtol=1e-10,
        atol=1e-14
    )

    if len(sol.t_events[0]):

        return sol.t_events[0][0]

    return np.nan


# =====================================================================
# 7. MODIFIED ODE: CURRENT-DEPENDENT DISSOLUTION
# =====================================================================

S0_DEMO = 1e6

J_CHECK = [100.0, 200.0, 500.0, 1000.0]


def ode_lifetime_hr(j, m):
    """
    Three-step catalyst:

    Step 1 is slow and its rate scales with current density:
        k1 = j/A

    Steps 2 and 3 are fast.

    Dissolution occurs only from X3. Its rate constant
    increases relative to catalytic turnover as:

        d3 = (k3/S0) * (j/J_REF)^m

    The numerical lifetime is obtained from the full ODE.
    """

    k = np.array([
        j / A,
        100.0,
        100.0
    ])

    d = np.zeros(3)

    d[2] = (
        k[2] / S0_DEMO
    ) * (j / J_REF)**m

    return (
        lifetime_numeric(
            k,
            d,
            steady_state_start(k)
        ) / 3600.0
    )


