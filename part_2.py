"""
Challenge Level 1 - Part 2
CURRENT-DEPENDENT CATALYST DISSOLUTION

IMPROVEMENT:
The effective catalyst dissolution rate depends on the
operating current density.

Original paper:
All rate constants are fixed, so the stability number S_num
is constant and lifetime = (N/v)*S_num, i.e. lifetime ~ 1/j.

Modified model:
Increasing current density generally involves changing the
electrode potential, which can also influence catalyst dissolution.
We represent this effect phenomenologically using one parameter, m:

    S_num(j) = S0 * (j / j_ref)^(-m)

    m = 0   -> No additional current dependence (original model)
    m > 0   -> Dissolution increases relative to catalytic turnover
              as current density increases.
    m < 0   -> Dissolution decreases relative to catalytic turnover
              as current density increases.

S0 is the stability number at the reference current density j_ref.

NOTE:
Current density is used as a proxy for operating conditions.
Electrode potential is not explicitly modelled.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp


# =====================================================================
# 1. CONSTANTS AND ASSUMPTIONS (SAME AS PART 1)
# =====================================================================

F = 96485.0                  # Faraday constant [C/mol]
N_E = 4                      # Electrons per oxygen molecule

SITE_DENSITY = 1e4           # Sites per nm^2 (paper's value)
NM2_PER_CM2 = 1e14
N_AVOGADRO = 6.02214076e23

N_TOTAL = (
    SITE_DENSITY * NM2_PER_CM2 / N_AVOGADRO
)                              # mol of sites per cm^2

# Combined constant:
# j [mA/cm^2] = A * k_rds [1/s]

A = N_TOTAL * N_E * F * 1000.0

J_REF = 100.0                # Reference current density [mA/cm^2]

M_NEW = 1.0                  # Current-dependence exponent
M_LIST = [-0.5, 0.0, 0.5, 1.0]


# =====================================================================
# 2. MODIFIED MODEL: CURRENT-DEPENDENT DISSOLUTION
# =====================================================================

def tau_seconds(S0, j, m):
    """
    Calculate lifetime [s] at current density j [mA/cm^2].

    Uses:
        S_num(j) = S0 * (j/J_REF)^(-m)

    and:
        tau = (N/v) * S_num
    """

    return A * S0 * J_REF**m / j**(1.0 + m)


def j_from_S0_tau(S0, tau_s, m):
    """
    Calculate current density [mA/cm^2] for a given
    reference stability number S0 and lifetime tau_s.
    """

    return (
        A * S0 * J_REF**m / tau_s
    ) ** (1.0 / (1.0 + m))


def log_S0_needed(j, tau_s, m):
    """
    Calculate log10 of the reference stability number S0
    required to achieve lifetime tau_s at current density j.
    """

    return (
        np.log10(tau_s * j / A)
        + m * np.log10(j / J_REF)
    )


