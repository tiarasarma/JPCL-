"""
Challenge Level 1 - Part 2
IMPROVEMENT: the wear-out (dissolution) speed depends on the voltage.

Paper's model: all rate constants are fixed numbers, so the stability number
S_num is a constant and lifetime = (N / v) * S_num, i.e. lifetime ~ 1 / current.

Real electrolyzer: you raise the current by raising the voltage, and the voltage
also changes how fast the catalyst dissolves. We add this with ONE new number, m:

    S_num(j) = S0 * (j / j_ref)^(-m)

  m = 0    -> dissolving ignores the voltage (the paper's model)
  m > 0    -> dissolving speeds up with voltage MORE than the step it competes with
              (stability gets worse at high current)
  m < 0    -> the opposite (stability gets better at high current)

S0 is the stability number measured at the reference current j_ref.

HOW TO RUN: paste the whole file into ONE cell in Google Colab and press
Shift+Enter (or save as part2.py and run `python part2.py`).
Needs numpy, scipy, matplotlib. Saves 3 PNG figures and prints 2 tables.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp

# =====================================================================
# Constants and assumptions (same as Part 1)
# =====================================================================
F = 96485.0                  # Faraday constant [C/mol]
N_E = 4                      # electrons per oxygen molecule
SITE_DENSITY = 1e4           # sites per nm^2 (paper's value)
NM2_PER_CM2 = 1e14
N_AVOGADRO = 6.02214076e23
N_TOTAL = SITE_DENSITY * NM2_PER_CM2 / N_AVOGADRO   # mol of sites per cm^2

# Handy combined constant:  j [mA/cm^2] = A * k_rds [1/s]
# (current = electrons per turnover * F * amount of sites * turnover rate)
A = N_TOTAL * N_E * F * 1000.0

J_REF = 100.0                # reference current density [mA/cm^2]
M_NEW = 1.0                  # voltage sensitivity used for the "new model" panels
M_LIST = [-0.5, 0.0, 0.5, 1.0]   # values compared in the line plot


# =====================================================================
# The extended model in three small formulas
# =====================================================================
def tau_seconds(S0, j, m):
    """Lifetime [s] at current density j [mA/cm^2].
    Paper's Eq. 10 with S_num = S0 * (j/J_REF)^(-m)."""
    return A * S0 * J_REF**m / j**(1.0 + m)


def j_from_S0_tau(S0, tau_s, m):
    """Current density [mA/cm^2] at which a catalyst with stability number S0
    (at J_REF) lasts tau_s seconds. (Solving the line above for j.)"""
    return (A * S0 * J_REF**m / tau_s) ** (1.0 / (1.0 + m))


def log_S0_needed(j, tau_s, m):
    """log10 of the S0 needed to last tau_s seconds at current density j."""
    return np.log10(tau_s * j / A) + m * np.log10(j / J_REF)


