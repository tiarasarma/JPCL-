# ---- Physical constants and assumptions (taken from the paper) ----
F = 96485.0                 # Faraday constant [C/mol of electrons]
N_E = 4                     # electrons per turnover (OER: 2H2O -> O2 + 4H+ + 4e-)
SITE_DENSITY = 1e4          # active sites per nm^2 of geometric area (paper's value)
NM2_PER_CM2 = 1e14          # 1 cm^2 = 1e14 nm^2
N_AVOGADRO = 6.02214076e23

# Total amount of active sites on 1 cm^2 of electrode [mol].
# 1e4 * 1e14 = 1e18 sites  ->  1.66e-6 mol. (The paper prints 1.66e6; the
# exponent should be NEGATIVE - see the report/log.)
N_TOTAL = SITE_DENSITY * NM2_PER_CM2 / N_AVOGADRO


def v_from_j(j_mA_cm2):
    """Reaction rate v [mol/s] from current density j [mA/cm^2]."""
    return (j_mA_cm2 / 1000.0) / (N_E * F)


def j_from_v(v):
    """Current density j [mA/cm^2] from reaction rate v [mol/s]."""
    return v * N_E * F * 1000.0


# Eq. 10:  tau = (N / v) * S_num
#   Fig 2A: pick (S_num, tau)  ->  v = N * S_num / tau  ->  j
#   Fig 2B: pick (j, tau)      ->  v from j  ->  S_num = tau * v / N

